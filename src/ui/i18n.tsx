export const LocaleContext = createContext<Language>("en");
export function useI18n() {
  const language = useContext(LocaleContext);
  return (key: Message) => (language === "zh" ? zh : en)[key];
}
export function errorMessage(
  error: unknown,
  t: ReturnType<typeof useI18n>,
): string {
  const message = error instanceof Error ? error.message : String(error);
  if (message in en) return t(message as Message);
  if (message.includes("Unsupported URL protocol"))
    return t("unsupportedProtocol");
  return t("requestFailed");
}
